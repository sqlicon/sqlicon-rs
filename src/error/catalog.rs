//! Informix error catalog lookup.

/// Looks up standard Informix SQLCODE or ISAM error text.
pub fn lookup_error_message(code: i32) -> Option<&'static str> {
    match code {
        -201 => Some("A syntax error has occurred near position: %s."),
        -206 => Some("The specified table (%s) is not in the database."),
        -217 => Some("Column (%s) not found in any table in the query (or SLV is undefined)."),
        -239 => Some("Could not insert new row - duplicate value in a UNIQUE INDEX column."),
        -256 => Some("Transaction not available."),
        -259 => Some("Connection is already in transaction."),
        -271 => Some("Could not insert new row into the table."),
        -272 => Some("No SELECT permission."),
        -273 => Some("No UPDATE permission."),
        -274 => Some("No INSERT permission."),
        -275 => Some("No DELETE permission."),
        -310 => Some("Table is already in exclusive mode."),
        -319 => Some("Exclusive lock required on table."),
        -329 => Some("Database (%s) not found or no system permission."),
        -346 => Some("Could not update row, a deadlock was detected."),
        -349 => Some("Database not selected yet."),
        -368 => Some("Incompatible sqlexec module."),
        -387 => Some("No connect permission."),
        -408 => Some("Invalid message type received from the sqlexec process."),
        -556 => Some("Cannot create index, table is in use by another user."),
        -619 => Some("A blob error has occurred in the front-end application."),
        -908 => Some("Socket connection to server (%s) failed. Check your server is reachable from this client on the host:port specified."),
        -912 => Some("Network error - Could not write to database server."),
        -913 => Some("Network error - Could not read from database server."),
        -937 => Some("User Defined Routine error."),
        -23101 => Some("Unable to load locale categories."),
        -23197 => Some("Database locale information mismatch."),
        // Common ISAM errors
        100 => Some("ISAM error: duplicate value for a record with unique key."),
        107 => Some("ISAM error: record is locked."),
        111 => Some("ISAM error: no record found."),
        126 => Some("ISAM error: bad row id."),
        143 => Some("ISAM error: deadlock detected."),
        149 => Some("ISAM error: Informix Database Server daemon is no longer running."),
        154 => Some("ISAM error: Lock Timeout Expired."),
        172 => Some("ISAM error: Unexpected internal error."),
        190 => Some("ISAM error: Transaction table overflow."),
        7350 => Some("Attempt to update a stale version of a row."),
        7351 => Some("Connection between secondary and primary has been lost."),
        7352 => Some("Operation (%s) can not be run on secondary node."),
        7353 => Some("The transaction cannot continue on the new primary server."),
        _ => None,
    }
}
